export function traduire(langue, cle, vars = {}) {
  const cat = CATALOGUES[langue] || CATALOGUES.fr;
  if (!(cle in cat)) throw new Error(`Clé de texte inconnue : ${cle}`);
  return cat[cle].replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

export function messageErreur(langue, code) {
  const cat = ERREURS[langue] || ERREURS.fr;
  return cat[code] || cat["E-INCONNUE"];
}
